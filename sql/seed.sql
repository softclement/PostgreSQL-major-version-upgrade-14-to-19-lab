-- ----- functions, procedure, operator, aggregate, cast, text search -----
CREATE FUNCTION app.order_total(p_order bigint, p_date date) RETURNS numeric
LANGUAGE sql STABLE
AS $$ SELECT COALESCE(SUM(line_total), 0) FROM app.order_items WHERE order_id = p_order AND order_date = p_date $$;

CREATE FUNCTION app.slugify(t text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE
RETURN lower(regexp_replace(t, '[^a-zA-Z0-9]+', '-', 'g'));

CREATE FUNCTION app.safe_div(a numeric, b numeric) RETURNS numeric
LANGUAGE sql IMMUTABLE
RETURN a / NULLIF(b, 0);
CREATE OPERATOR app.%% (LEFTARG = numeric, RIGHTARG = numeric, FUNCTION = app.safe_div);

CREATE AGGREGATE app.concat_all(text) (SFUNC = textcat, STYPE = text);

CREATE FUNCTION app.address_to_text(a app.address) RETURNS text
LANGUAGE sql IMMUTABLE
RETURN a.street || ', ' || a.city || ' ' || a.pincode;
CREATE CAST (app.address AS text) WITH FUNCTION app.address_to_text(app.address);

