CREATE FUNCTION audit.ddl_logger() RETURNS event_trigger LANGUAGE plpgsql AS $$
DECLARE r record;
BEGIN
  FOR r IN SELECT * FROM pg_event_trigger_ddl_commands() LOOP
    INSERT INTO audit.ddl_log (event, tag, object) VALUES (TG_EVENT, r.command_tag, r.object_identity);
  END LOOP;
END $$;
GRANT USAGE  ON SCHEMA audit TO PUBLIC;
GRANT INSERT ON audit.ddl_log TO PUBLIC;
GRANT USAGE  ON SEQUENCE audit.ddl_log_log_id_seq TO PUBLIC;
CREATE EVENT TRIGGER evt_ddl_log ON ddl_command_end EXECUTE FUNCTION audit.ddl_logger();

