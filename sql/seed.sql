CREATE FUNCTION audit.log_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    INSERT INTO audit.change_log (table_name, op, row_data) VALUES (TG_TABLE_NAME, TG_OP, to_jsonb(OLD));
    RETURN OLD;
  END IF;
  INSERT INTO audit.change_log (table_name, op, row_data) VALUES (TG_TABLE_NAME, TG_OP, to_jsonb(NEW));
  RETURN NEW;
END $$;
CREATE TRIGGER trg_customers_audit AFTER INSERT OR UPDATE OR DELETE ON app.customers
  FOR EACH ROW EXECUTE FUNCTION audit.log_change();

CREATE FUNCTION app.touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at := now(); RETURN NEW; END $$;
CREATE TRIGGER trg_products_touch BEFORE UPDATE ON app.products
  FOR EACH ROW WHEN ((OLD.sku, OLD.name, OLD.price, OLD.specs, OLD.rating) IS DISTINCT FROM
                     (NEW.sku, NEW.name, NEW.price, NEW.specs, NEW.rating)) EXECUTE FUNCTION app.touch_updated_at();

CREATE FUNCTION app.block_truncate() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'TRUNCATE blocked on %', TG_TABLE_NAME; END $$;
CREATE TRIGGER trg_products_no_truncate BEFORE TRUNCATE ON app.products
  FOR EACH STATEMENT EXECUTE FUNCTION app.block_truncate();

CREATE FUNCTION app.check_qty() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN IF NEW.qty > 1000 THEN RAISE EXCEPTION 'qty too large'; END IF; RETURN NULL; END $$;
CREATE CONSTRAINT TRIGGER ctrg_items_qty AFTER INSERT ON app.order_items
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION app.check_qty();

CREATE FUNCTION app.v_products_ins() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN INSERT INTO app.products (sku, name, price) VALUES (NEW.sku, NEW.name, NEW.price); RETURN NEW; END $$;
CREATE TRIGGER trg_v_products_ins INSTEAD OF INSERT ON app.v_products_public
  FOR EACH ROW EXECUTE FUNCTION app.v_products_ins();

