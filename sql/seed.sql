CREATE PROCEDURE app.place_order(p_customer bigint, p_product int, p_qty int)
LANGUAGE plpgsql
AS $$
DECLARE v_id bigint; v_date date := current_date; v_price numeric;
BEGIN
  SELECT price INTO v_price FROM app.products WHERE product_id = p_product;
  INSERT INTO app.orders (customer_id, order_date) VALUES (p_customer, v_date) RETURNING order_id INTO v_id;
  INSERT INTO app.order_items (order_id, order_date, line_no, product_id, qty, unit_price)
  VALUES (v_id, v_date, 1, p_product, p_qty, v_price);
  UPDATE app.orders SET total = app.order_total(v_id, v_date) WHERE order_id = v_id AND order_date = v_date;
END $$;

